import os
import subprocess
import sys
import json
from pathlib import Path
import litellm

# Ensure we use ollama provider
litellm.drop_params = True

SLM_MODELS = [
    "ollama/llama3",
    "ollama/mistral",
    "ollama/phi3"
]

DATASETS = [
    {"name": "complex", "path": "data/scenarios_complex.json"},
    {"name": "simple", "path": "data/scenarios.json"}
]

python = sys.executable

def pull_ollama_model(model_id: str):
    # e.g., 'ollama/llama3' -> 'llama3'
    base_model = model_id.split("/")[-1]
    print(f"\n[SLM Pipeline] Pulling model {base_model} via Ollama...")
    subprocess.run(["ollama", "pull", base_model], check=True)

def main():
    print("============================================================")
    print("InfraSecBench Phase 5: Local SLM Pipeline")
    print("============================================================\n")

    for model_id in SLM_MODELS:
        # Pull model to ensure it's available locally
        pull_ollama_model(model_id)
        
        # Run against both datasets
        for dataset in DATASETS:
            print(f"\n[SLM Pipeline] Generating {dataset['name']} scenarios for {model_id}...")
            
            # Use generate_iac.py but patch the MODEL_REGISTRY dynamically via command line
            # Wait, generate_iac.py only accepts models in MODEL_REGISTRY.
            # We can write a quick patch or pass an env var. Let's just create a small generator logic here to keep it reliable.
            
            with open(dataset["path"], "r") as f:
                scenarios = json.load(f)
                
            out_dir = Path("data/generated") / dataset["name"] / model_id.replace("ollama/", "")
            out_dir.mkdir(parents=True, exist_ok=True)
            
            for i, scenario in enumerate(scenarios):
                sid = scenario["id"]
                tool = scenario.get("tool", "txt")
                ext = "yaml" if tool in ["CloudFormation", "Kubernetes"] else "tf"
                out_file = out_dir / sid / f"main.{ext}"
                
                if out_file.exists():
                    continue
                    
                out_file.parent.mkdir(parents=True, exist_ok=True)
                
                # Basic prompt
                prompt = f"""You are an expert infrastructure architect. Generate {tool} code for the following scenario.
SCENARIO: {scenario['prompt']}
Do not include explanations, just the markdown code block."""

                try:
                    res = litellm.completion(
                        model=model_id,
                        messages=[{"role": "user", "content": prompt}],
                        temperature=0.2,
                        num_ctx=4096
                    )
                    content = res.choices[0].message.content
                    
                    # Extract code block
                    code = content
                    if "```" in content:
                        blocks = content.split("```")
                        if len(blocks) >= 3:
                            code = blocks[1]
                            if "\n" in code:
                                code = code[code.find("\n")+1:]
                    
                    if not code.strip():
                        code = f"# No code generated by model\n# Raw output:\n# {content.replace('\n', '\n# ')}"
                        
                    out_file.write_text(code, encoding="utf-8")
                        
                    print(f"[{i+1}/{len(scenarios)}] Generated {sid}")
                except Exception as e:
                    print(f"[{i+1}/{len(scenarios)}] Error on {sid}: {e}")

    # Now that all SLMs are generated, run the standard scanning and parsing pipeline
    print("\n[SLM Pipeline] Generation complete. Running Security Scanners...")
    subprocess.run([python, "src/run_scanners.py"], check=True)
    
    print("\n[SLM Pipeline] Parsing results...")
    subprocess.run([python, "src/parse_results.py"], check=True)
    
    print("\n[SLM Pipeline] Generating visualisations...")
    subprocess.run([python, "src/visualise.py"], check=True)
    
    print("\n[SLM Pipeline] Complete!")

if __name__ == "__main__":
    main()
